// Project-local development provisioning, no Windows service and no VPS connection.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { randomBytes } from "node:crypto";
import { execFileSync } from "node:child_process";
const root = resolve(".local/postgres"),
  bin = join(root, "bin-dist/pgsql/bin"),
  data = join(root, "data");
const envPath = resolve(".local/backend.env");
if (!existsSync(join(bin, "initdb.exe")))
  throw new Error("Binaries PostgreSQL belum siap.");
mkdirSync(root, { recursive: true });
if (!existsSync(data)) {
  const password = randomBytes(32).toString("base64url");
  const passwordFile = join(root, "init-password");
  writeFileSync(passwordFile, password, { flag: "wx" });
  execFileSync(
    join(bin, "initdb.exe"),
    [
      "-D",
      data,
      "-U",
      "wapala_dev",
      "--auth-host=scram-sha-256",
      "--auth-local=scram-sha-256",
      "--pwfile=" + passwordFile,
      "--encoding=UTF8",
      "--locale=C",
    ],
    { windowsHide: true, stdio: "pipe" },
  );
  const database = "postgresql://wapala_dev:" + password + "@127.0.0.1:54329/";
  writeFileSync(
    envPath,
    [
      "DATABASE_URL=" + database + "wapala",
      "TEST_DATABASE_URL=" + database + "wapala_test",
      "APP_URL=http://127.0.0.1:3000",
      "SECURITY_KEY=" + randomBytes(32).toString("base64"),
      "EMAIL_MODE=sink",
      "WAPALA_MODE=backend",
      "TRUST_PROXY=false",
    ].join("\n") + "\n",
    { flag: "wx" },
  );
}
if (!existsSync(envPath))
  throw new Error(
    "Environment lokal belum ada; tidak membuat ulang credential cluster yang sudah ada.",
  );
// Migrate only the environment generated by this provisioner after a Windows-reserved port failure.
const localEnvironment = readFileSync(envPath, "utf8");
if (localEnvironment.includes("@127.0.0.1:55432/"))
  writeFileSync(
    envPath,
    localEnvironment.replaceAll("@127.0.0.1:55432/", "@127.0.0.1:54329/"),
  );
const url = new URL(
  readFileSync(envPath, "utf8")
    .split("\n")
    .find((l) => l.startsWith("DATABASE_URL="))!
    .slice(13),
);
try {
  execFileSync(join(bin, "pg_ctl.exe"), ["-D", data, "status"], {
    windowsHide: true,
    stdio: "pipe",
  });
} catch {
  execFileSync(
    join(bin, "pg_ctl.exe"),
    [
      "-D",
      data,
      "-l",
      join(root, "server.log"),
      "-o",
      "-h 127.0.0.1 -p 54329",
      "-w",
      "start",
    ],
    { windowsHide: true, stdio: "ignore" },
  );
}
const pgEnv = { ...process.env, PGPASSWORD: url.password };
for (const db of ["wapala", "wapala_test"]) {
  const result = execFileSync(
    join(bin, "psql.exe"),
    [
      "-h",
      "127.0.0.1",
      "-p",
      "54329",
      "-U",
      "wapala_dev",
      "-d",
      "postgres",
      "-w",
      "-Atc",
      `SELECT 1 FROM pg_database WHERE datname='${db}'`,
    ],
    { env: pgEnv, windowsHide: true, encoding: "utf8", stdio: "pipe" },
  );
  if (!result.trim())
    execFileSync(
      join(bin, "createdb.exe"),
      ["-h", "127.0.0.1", "-p", "54329", "-U", "wapala_dev", "-w", db],
      { env: pgEnv, windowsHide: true, stdio: "pipe" },
    );
}
console.log(
  "PostgreSQL development siap di localhost:54329; credentials ada di .local/backend.env (tidak ditampilkan).",
);
